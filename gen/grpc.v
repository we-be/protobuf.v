module gen

import strings

// gRPC client stub generator: one <Service>Client struct per service with
// a method per unary rpc, calling grpc.Client.unary with the full method
// path. Streaming rpcs are skipped with a comment until the transport
// grows streaming. Stubs share the message code's module, so request and
// response types resolve without imports.

// CamelCase rpc name to a V method name: WatchAll -> watch_all
fn snake(name string) string {
	mut out := []u8{cap: name.len + 4}
	for i, c in name {
		if c >= `A` && c <= `Z` {
			if i > 0 {
				out << `_`
			}
			out << c + 32
		} else {
			out << c
		}
	}
	return out.bytestr()
}

pub fn generate_grpc(f File, opts GenOpts) !string {
	return generate_grpc_set(FileSet{ root: f, files: [f] }, opts)
}

pub fn generate_grpc_set(fs FileSet, opts GenOpts) !string {
	if fs.root.services.len == 0 {
		return error('no services in file')
	}
	mut g := Gen{
		files:    fs.files
		root_pkg: fs.root.package
		json:     opts.json
	}
	for file in fs.files {
		g.register_file(file)!
	}
	g.set_cur(fs.root)
	mut b := strings.new_builder(4096)
	b.writeln('// Code generated by protobuf.gen. DO NOT EDIT.')
	b.writeln('module ${opts.module_name}')
	b.writeln('')
	b.writeln('import grpc')
	for svc in fs.root.services {
		prefix := if fs.root.package != '' {
			'/${fs.root.package}.${svc.name}/'
		} else {
			'/${svc.name}/'
		}
		b.writeln('')
		b.writeln('pub struct ${svc.name}Client {')
		b.writeln('pub mut:')
		b.writeln('\tc grpc.Client')
		b.writeln('}')
		for m in svc.methods {
			in_sym := g.resolve_in_pkg([], m.input) or {
				return error('service ${svc.name}: unknown type `${m.input}` for rpc ${m.name}')
			}
			out_sym := g.resolve_in_pkg([], m.output) or {
				return error('service ${svc.name}: unknown type `${m.output}` for rpc ${m.name}')
			}
			if in_sym.is_enum || out_sym.is_enum {
				return error('service ${svc.name}: rpc ${m.name} types must be messages')
			}
			b.writeln('')
			if m.client_streaming || m.server_streaming {
				dir := if m.client_streaming && m.server_streaming {
					'bidirectional'
				} else if m.client_streaming {
					'client'
				} else {
					'server'
				}
				b.writeln('// rpc ${m.name} skipped: ${dir} streaming is not supported yet')
				continue
			}
			b.writeln('pub fn (mut x ${svc.name}Client) ${sanitize(snake(m.name))}(req ${in_sym.vname}) !${out_sym.vname} {')
			b.writeln("\tresp := x.c.unary('${prefix}${m.name}', req.encode())!")
			b.writeln('\treturn ${out_sym.vname}.decode(resp)!')
			b.writeln('}')
		}
		g.emit_connect_service(mut b, svc, prefix)!
	}
	return b.str()
}

// server side: a handler interface for the user to implement plus a
// dispatch struct satisfying grpc.Service for ConnectServer.mount
fn (mut g Gen) emit_connect_service(mut b strings.Builder, svc Service, prefix string) ! {
	mut unary := []Method{}
	for m in svc.methods {
		if !m.client_streaming && !m.server_streaming {
			unary << m
		}
	}
	if unary.len == 0 {
		b.writeln('')
		b.writeln('// service ${svc.name}: no unary methods, server glue skipped')
		return
	}
	b.writeln('')
	b.writeln('pub interface ${svc.name}Handler {')
	b.writeln('mut:')
	for m in unary {
		in_sym := g.resolve_in_pkg([], m.input) or { return error('unreachable') }
		out_sym := g.resolve_in_pkg([], m.output) or { return error('unreachable') }
		b.writeln('\t${sanitize(snake(m.name))}(req ${in_sym.vname}) !${out_sym.vname}')
	}
	b.writeln('}')
	b.writeln('')
	b.writeln('pub struct ${svc.name}Service {')
	b.writeln('pub mut:')
	b.writeln('\th ${svc.name}Handler')
	b.writeln('}')
	b.writeln('')
	b.writeln('pub fn (mut s ${svc.name}Service) call(path string, codec grpc.Codec, body []u8) !([]u8, bool) {')
	b.writeln('\tmatch path {')
	for m in unary {
		in_sym := g.resolve_in_pkg([], m.input) or { return error('unreachable') }
		b.writeln("\t\t'${prefix}${m.name}' {")
		if g.json {
			b.writeln('\t\t\treq := if codec == .json {')
			b.writeln('\t\t\t\t${in_sym.vname}.from_json(body.bytestr())!')
			b.writeln('\t\t\t} else {')
			b.writeln('\t\t\t\t${in_sym.vname}.decode(body)!')
			b.writeln('\t\t\t}')
		} else {
			b.writeln('\t\t\tif codec == .json {')
			b.writeln('\t\t\t\treturn grpc.StatusError{')
			b.writeln('\t\t\t\t\tstatus: grpc.Status{')
			b.writeln('\t\t\t\t\t\tcode:    .unimplemented')
			b.writeln("\t\t\t\t\t\tmessage: 'JSON codec unavailable: generate with -json'")
			b.writeln('\t\t\t\t\t}')
			b.writeln('\t\t\t\t}')
			b.writeln('\t\t\t}')
			b.writeln('\t\t\treq := ${in_sym.vname}.decode(body)!')
		}
		b.writeln('\t\t\tresp := s.h.${sanitize(snake(m.name))}(req)!')
		if g.json {
			b.writeln('\t\t\tout := if codec == .json {')
			b.writeln('\t\t\t\tresp.json().bytes()')
			b.writeln('\t\t\t} else {')
			b.writeln('\t\t\t\tresp.encode()')
			b.writeln('\t\t\t}')
			b.writeln('\t\t\treturn out, true')
		} else {
			b.writeln('\t\t\treturn resp.encode(), true')
		}
		b.writeln('\t\t}')
	}
	b.writeln('\t\telse {')
	b.writeln('\t\t\treturn []u8{}, false')
	b.writeln('\t\t}')
	b.writeln('\t}')
	b.writeln('}')
}
